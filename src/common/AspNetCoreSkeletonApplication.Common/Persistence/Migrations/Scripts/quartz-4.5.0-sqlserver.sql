  [SCHED_NAME] nvarchar(120) NOT NULL,
  [ENTRY_ID] nvarchar(140) NOT NULL,
  [INSTANCE_NAME] nvarchar(200) NOT NULL,
  [JOB_NAME] nvarchar(150) NOT NULL,
